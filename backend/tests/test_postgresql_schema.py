"""PostgreSQL DDL contracts, including offline reproducible Alembic output."""

import io

import sqlalchemy as sa
import pytest
from alembic import command
from alembic.config import Config
from alembic.util import CommandError

from app.storage.schema import BACKEND_ROOT, add_coordination_metadata, baseline_metadata


def test_frozen_baseline_preserves_history_types_and_order():
    baseline = baseline_metadata()
    assert len(baseline.tables) == 41
    for name in ("chat_messages", "react_calls"):
        assert baseline.tables[name].c.legacy_order.identity is not None
    for name, column in (
        ("agent_predictions", "facts_json"),
        ("agent_live_prediction_snapshots", "snapshot_json"),
        ("quality_evidence_bundles", "payload_json"),
    ):
        assert isinstance(baseline.tables[name].c[column].type, sa.Text)
    assert isinstance(baseline.tables["stock_daily_bars"].c.close.type, sa.Double)


def test_frozen_schema_has_deferrable_foreign_keys_and_complete_metadata():
    historical = baseline_metadata()
    add_coordination_metadata(historical)
    assert len(historical.tables) == 45
    for table in historical.tables.values():
        assert len(table.primary_key.columns) > 0
        for constraint in table.foreign_key_constraints:
            assert constraint.deferrable
            assert constraint.initially == "DEFERRED"
            for element in constraint.elements:
                assert element.column is not None


def test_alembic_offline_upgrade_is_complete_and_credential_free(monkeypatch):
    monkeypatch.setenv("LIMITUPLAB_DATABASE_URL", "postgresql://unused:secret@localhost/unused")
    output = io.StringIO()
    config = Config(str(BACKEND_ROOT / "alembic.ini"), output_buffer=output)
    command.upgrade(config, "head", sql=True)
    sql = output.getvalue()
    assert sql.count("CREATE TABLE ") == 57  # Includes user run-control operation receipts.
    assert "CREATE TABLE run_control_operations " in sql
    assert "control_revision BIGINT NOT NULL DEFAULT 0" in sql
    for table in ("checkpoints", "checkpoint_blobs", "checkpoint_writes", "agent_tool_results"):
        assert f"CREATE TABLE {table} " in sql
    for table in (
        "long_term_memories", "memory_owner_versions",
        "memory_operation_receipts", "memory_relations",
        "memory_extraction_jobs",
    ):
        assert f"CREATE TABLE {table} " in sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "quality_evaluations_terminal_no_update" in sql
    assert "WHERE active = 1" in sql
    assert "0003_single_champion" in sql
    assert "one_champion_policy" in sql
    assert "0004_drop_quality_tables" in sql
    assert 'DROP TABLE IF EXISTS "quality_cases"' in sql
    assert "secret" not in sql
    assert "PRAGMA" not in sql


@pytest.mark.parametrize("operation", ["revision", "check"])
def test_autogeneration_is_explicitly_rejected_without_writing_revisions(postgresql_database, operation):
    engine = sa.create_engine(postgresql_database, poolclass=sa.pool.NullPool)
    before = set((BACKEND_ROOT / "migrations" / "versions").iterdir())
    try:
        with engine.connect() as connection:
            config = Config(str(BACKEND_ROOT / "alembic.ini"))
            config.attributes["connection"] = connection
            with pytest.raises(CommandError, match="hand-written Alembic revisions"):
                if operation == "revision":
                    command.revision(config, message="must not be generated", autogenerate=True)
                else:
                    command.check(config)
    finally:
        engine.dispose()
    assert set((BACKEND_ROOT / "migrations" / "versions").iterdir()) == before
